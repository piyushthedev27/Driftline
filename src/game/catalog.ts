  THEMES.find((t) => t.id === id) || THEMES[0];
export const recordKey = (mapId: string, vehicleId: string) =>
  `${mapId}:${vehicleId}`;
export function validRecords(value: unknown): Record<string, number> {
  if (!value || typeof value !== "object") return {};
  return Object.fromEntries(
    Object.entries(value).filter(
      ([key, time]) =>
        MAPS.some((m) => VEHICLES.some((v) => key === recordKey(m.id, v.id))) &&
        typeof time === "number" &&
        Number.isFinite(time) &&
        time > 0,
    ),
  );
}
